"""Build the quarto-vcci extensions from the brand system.

    python quarto-vcci/build.py            write _extensions/vcci/<format>/ and the chart themes from src/ and brand-assets/
    python quarto-vcci/build.py --check    exit 1 if the committed _extensions/ or chart themes differ from a fresh build

Single source:
  brand-assets/brand-tokens.json, 03_Fonts, 01_Logo, 06_Templates/Word/VCCI_Report.dotx   (brand system)
  quarto-vcci/src/shared/   vcci.typ (Typst layer), vcci.lua (block styles for Typst and Word)
  quarto-vcci/src/formats/<format>/   _extension.yml, template.typ, typst-show.typ
Each extension is self-contained (Quarto cannot share files between extensions), so the shared parts are copied in:
  typst-template.typ = generated tokens + logo + shared/vcci.typ + formats/<format>/template.typ
Chart themes (matplotlib, ggplot2, Stata): quarto-vcci/src/charts/ with {{...}} filled from brand-tokens.json ->
  quarto-vcci/charts/ and brand-assets/06_Templates/Charts/ (for users without Quarto)
"""
import filecmp, json, os, re, shutil, sys, tempfile, time, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ASSETS = os.path.join(ROOT, 'brand-assets')
SRC = os.path.join(HERE, 'src')
OUT = os.path.join(HERE, '_extensions', 'vcci')
FORMATS = sorted(d for d in os.listdir(os.path.join(SRC, 'formats')) if os.path.isdir(os.path.join(SRC, 'formats', d)))
GENERATED = '// GENERATED by quarto-vcci/build.py from brand-assets and quarto-vcci/src. Do not edit; edit the sources.\n'


def tokens_typ():
    t = json.load(open(os.path.join(ASSETS, 'brand-tokens.json'), encoding='utf-8'))
    col = t['colour']
    slug = lambda n: n.lower().replace('vcci ', '').replace('drum ', '').replace(' ', '-')
    core = {slug(n): v['hex'] for n, v in col.items() if isinstance(v, dict) and 'hex' in v}
    lines = [GENERATED, f'// brand-tokens.json version {t["version"]}']
    lines.append('#let VCCI = (' + ', '.join(f'{k}: rgb("{h}")' for k, h in core.items()) + ')')
    lines.append('#let VCCI-SCALE = (' + ', '.join(
        f'{name}: (' + ', '.join(f'"{g}": rgb("{h}")' for g, h in steps.items()) + ')'
        for name, steps in col['scales'].items() if name != 'note') + ')')
    lines.append('#let VCCI-STATUS = (' + ', '.join(
        f'{n.lower()}: (strong: rgb("{v["strong"]}"), background: rgb("{v["background"]}"))'
        for n, v in col['status'].items() if isinstance(v, dict)) + ')')
    dv = t['dataviz']
    lines.append('#let VCCI-SERIES = (' + ', '.join(f'rgb("{h}")' for _, h in dv['categorical']) + ',)')
    lines.append('#let VCCI-SEQUENTIAL = (' + ', '.join(f'rgb("{h}")' for h in dv['sequential_7']) + ',)')
    lines.append('#let VCCI-DIVERGING = (' + ', '.join(f'rgb("{h}")' for h in dv['diverging_7']) + ',)')
    ty = t['typography']
    lines.append(f'#let VCCI-FONT = (display: "{ty["display"]["family"]}", text: "{ty["text"]["family"]}")')
    return '\n'.join(lines) + '\n'


def typst_str(s):
    return '"' + s.strip().replace('\\', '\\\\').replace('"', '\\"') + '"'


def svg_const(name, path):
    return f'#let {name} = {typst_str(open(path, encoding="utf-8").read())}\n'


def ring_const():
    """Drum-ring line art (white lines, gold star) on a transparent ground, for blue fields."""
    svg = open(os.path.join(ASSETS, '04_Graphics', 'VCCI_Drum-Ring_Line_Gold-on-Blue.svg'), encoding='utf-8').read()
    svg = re.sub(r'<rect [^>]*/>', '', svg, count=1)
    svg = svg.replace('opacity="0.22"', 'opacity="0.15"').replace('opacity="0.75"', 'opacity="0.5"')   # as subtle as the Word covers
    return f'#let VCCI-RING = {typst_str(svg)}\n'


def heroes_const():
    """The 24 hero icons, gold (for blue fields) and blue-gold (for light pages), keyed "01".."24"."""
    base = os.path.join(ASSETS, '05_Icons', 'Hero', 'SVG')
    entries = []
    for f in sorted(os.listdir(os.path.join(base, 'Gold-on-dark'))):
        m = re.match(r'VCCI_Hero_(\d\d)_(.+)\.svg$', f)
        if not m: continue
        gold = open(os.path.join(base, 'Gold-on-dark', f), encoding='utf-8').read()
        blue = open(os.path.join(base, 'Blue-Gold', f), encoding='utf-8').read()
        entries.append(f'"{m.group(1)}": (slug: "{m.group(2)}", gold: {typst_str(gold)}, blue: {typst_str(blue)})')
    return '#let VCCI-HERO = (\n  ' + ',\n  '.join(entries) + ',\n)\n'


