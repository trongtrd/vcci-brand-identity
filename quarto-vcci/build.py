"""Build the quarto-vcci extensions from the brand system.

    python quarto-vcci/build.py            write _extensions/vcci/<format>/ from src/ and brand-assets/
    python quarto-vcci/build.py --check    exit 1 if the committed _extensions/ differ from a fresh build

Single source:
  brand-assets/brand-tokens.json, 03_Fonts, 01_Logo, 06_Templates/Word/VCCI_Report.dotx   (brand system)
  quarto-vcci/src/shared/   vcci.typ (Typst layer), vcci.lua (block styles for Typst and Word)
  quarto-vcci/src/formats/<format>/   _extension.yml, template.typ, typst-show.typ
Each extension is self-contained (Quarto cannot share files between extensions), so the shared parts are copied in:
  typst-template.typ = generated tokens + logo + shared/vcci.typ + formats/<format>/template.typ
"""
import filecmp, json, os, re, shutil, sys, tempfile, time, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ASSETS = os.path.join(ROOT, 'brand-assets')
SRC = os.path.join(HERE, 'src')
OUT = os.path.join(HERE, '_extensions', 'vcci')
FORMATS = sorted(d for d in os.listdir(os.path.join(SRC, 'formats')) if os.path.isdir(os.path.join(SRC, 'formats', d)))
GENERATED = '// GENERATED by quarto-vcci/build.py from brand-assets and quarto-vcci/src. Do not edit; edit the sources.\n'


def tokens_typ():
    t = json.load(open(os.path.join(ASSETS, 'brand-tokens.json'), encoding='utf-8'))
    col = t['colour']
    slug = lambda n: n.lower().replace('vcci ', '').replace('drum ', '').replace(' ', '-')
    core = {slug(n): v['hex'] for n, v in col.items() if isinstance(v, dict) and 'hex' in v}
    lines = [GENERATED, f'// brand-tokens.json version {t["version"]}']
    lines.append('#let VCCI = (' + ', '.join(f'{k}: rgb("{h}")' for k, h in core.items()) + ')')
    lines.append('#let VCCI-SCALE = (' + ', '.join(
        f'{name}: (' + ', '.join(f'"{g}": rgb("{h}")' for g, h in steps.items()) + ')'
        for name, steps in col['scales'].items() if name != 'note') + ')')
    lines.append('#let VCCI-STATUS = (' + ', '.join(
        f'{n.lower()}: (strong: rgb("{v["strong"]}"), background: rgb("{v["background"]}"))'
        for n, v in col['status'].items() if isinstance(v, dict)) + ')')
    dv = t['dataviz']
    lines.append('#let VCCI-SERIES = (' + ', '.join(f'rgb("{h}")' for _, h in dv['categorical']) + ',)')
    lines.append('#let VCCI-SEQUENTIAL = (' + ', '.join(f'rgb("{h}")' for h in dv['sequential_7']) + ',)')
    lines.append('#let VCCI-DIVERGING = (' + ', '.join(f'rgb("{h}")' for h in dv['diverging_7']) + ',)')
    ty = t['typography']
    lines.append(f'#let VCCI-FONT = (display: "{ty["display"]["family"]}", text: "{ty["text"]["family"]}")')
    return '\n'.join(lines) + '\n'


def typst_str(s):
    return '"' + s.strip().replace('\\', '\\\\').replace('"', '\\"') + '"'


def svg_const(name, path):
    return f'#let {name} = {typst_str(open(path, encoding="utf-8").read())}\n'


def ring_const():
    """Drum-ring line art (white lines, gold star) on a transparent ground, for blue fields."""
    svg = open(os.path.join(ASSETS, '04_Graphics', 'VCCI_Drum-Ring_Line_Gold-on-Blue.svg'), encoding='utf-8').read()
    svg = re.sub(r'<rect [^>]*/>', '', svg, count=1)
    svg = svg.replace('opacity="0.22"', 'opacity="0.15"').replace('opacity="0.75"', 'opacity="0.5"')   # as subtle as the Word covers
    return f'#let VCCI-RING = {typst_str(svg)}\n'


def heroes_const():
    """The 24 hero icons, gold (for blue fields) and blue-gold (for light pages), keyed "01".."24"."""
    base = os.path.join(ASSETS, '05_Icons', 'Hero', 'SVG')
    entries = []
    for f in sorted(os.listdir(os.path.join(base, 'Gold-on-dark'))):
        m = re.match(r'VCCI_Hero_(\d\d)_(.+)\.svg$', f)
        if not m: continue
        gold = open(os.path.join(base, 'Gold-on-dark', f), encoding='utf-8').read()
        blue = open(os.path.join(base, 'Blue-Gold', f), encoding='utf-8').read()
        entries.append(f'"{m.group(1)}": (slug: "{m.group(2)}", gold: {typst_str(gold)}, blue: {typst_str(blue)})')
    return '#let VCCI-HERO = (\n  ' + ',\n  '.join(entries) + ',\n)\n'


# styleId, name, type, basedOn, extra XML (pPr/rPr). Sizes in half-points; colours from the brand palette.
PANDOC_STYLES = [
    ('BodyText', 'Body Text', 'paragraph', 'Normal', ''),
    ('FirstParagraph', 'First Paragraph', 'paragraph', 'BodyText', ''),
    ('Compact', 'Compact', 'paragraph', 'BodyText', '<w:pPr><w:spacing w:before="36" w:after="36"/></w:pPr>'),
    ('Author', 'Author', 'paragraph', 'Normal', '<w:rPr><w:b/><w:color w:val="161A26"/></w:rPr>'),
    ('Date', 'Date', 'paragraph', 'Normal', '<w:rPr><w:color w:val="5C6478"/></w:rPr>'),
    ('Abstract', 'Abstract', 'paragraph', 'VCCICallout', ''),
    ('AbstractTitle', 'Abstract Title', 'paragraph', 'VCCILabel', ''),
    ('Bibliography', 'Bibliography', 'paragraph', 'Normal', '<w:pPr><w:ind w:left="360" w:hanging="360"/></w:pPr>'),
    ('BlockText', 'Block Text', 'paragraph', 'Quote', ''),
    ('ImageCaption', 'Image Caption', 'paragraph', 'Caption', ''),
    ('TableCaption', 'Table Caption', 'paragraph', 'Caption', ''),
    ('Figure', 'Figure', 'paragraph', 'Normal', '<w:pPr><w:keepNext/></w:pPr>'),
    ('CaptionedFigure', 'Captioned Figure', 'paragraph', 'Figure', ''),
    ('TOCHeading', 'TOC Heading', 'paragraph', 'VCCITOCHeading', ''),
    ('SourceCode', 'Source Code', 'paragraph', 'Normal', '<w:rPr><w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/><w:sz w:val="17"/></w:rPr>'),
    ('DefinitionTerm', 'Definition Term', 'paragraph', 'Normal', '<w:rPr><w:b/></w:rPr>'),
    ('Definition', 'Definition', 'paragraph', 'Normal', ''),
    ('BodyTextChar', 'Body Text Char', 'character', 'DefaultParagraphFont', ''),
    ('VerbatimChar', 'Verbatim Char', 'character', 'DefaultParagraphFont', '<w:rPr><w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/></w:rPr>'),
    ('SectionNumber', 'Section Number', 'character', 'DefaultParagraphFont', ''),
]


def reference_docx(dst):
    """VCCI_Report.dotx as a .docx reference document whose built-in 'Table' style is the VCCI table style."""
    src = os.path.join(ASSETS, '06_Templates', 'Word', 'VCCI_Report.dotx')
    z = zipfile.ZipFile(src)
    files = {n: z.read(n) for n in z.namelist()}
    files['[Content_Types].xml'] = files['[Content_Types].xml'].replace(
        b'wordprocessingml.template.main+xml', b'wordprocessingml.document.main+xml')
    st = files['word/styles.xml'].decode('utf-8')
    vt = re.search(r'<w:style w:type="table"[^>]*w:styleId="VCCITable".*?</w:style>', st, re.S).group(0)
    clone = re.sub(r'w:styleId="VCCITable"', 'w:styleId="Table"', vt, count=1)
    clone = re.sub(r'<w:name w:val="[^"]*"/>', '<w:name w:val="Table"/>', clone, count=1)
    st = re.sub(r'<w:style w:type="table"[^>]*w:styleId="Table".*?</w:style>', '', st, flags=re.S)
    st = st.replace('</w:styles>', clone + '</w:styles>')
    # Pandoc's own paragraph and character styles, based on the VCCI ones (Word falls back to Normal for undefined styles)
    for sid, name, kind, based, extra in PANDOC_STYLES:
        if f'w:styleId="{sid}"' in st: continue
        st = st.replace('</w:styles>', f'<w:style w:type="{kind}" w:customStyle="1" w:styleId="{sid}"><w:name w:val="{name}"/>'
                                       f'<w:basedOn w:val="{based}"/><w:qFormat/>{extra}</w:style></w:styles>')
    files['word/styles.xml'] = st.encode('utf-8')
    # body of the reference document is irrelevant to Pandoc; keep it, but give zip entries a fixed date so builds are reproducible
    with zipfile.ZipFile(dst, 'w', zipfile.ZIP_DEFLATED) as out:
        for n in files:
            out.writestr(zipfile.ZipInfo(n, date_time=(2026, 1, 1, 0, 0, 0)), files[n], zipfile.ZIP_DEFLATED)


def build(out_root):
    shared_typ = open(os.path.join(SRC, 'shared', 'vcci.typ'), encoding='utf-8').read()
    logos = (svg_const('VCCI-LOGO', os.path.join(ASSETS, '01_Logo', 'SVG', 'VCCI_Logo_Primary.svg'))
             + svg_const('VCCI-LOGO-PLATE', os.path.join(ASSETS, '01_Logo', 'SVG', 'VCCI_Logo_Primary_Plate.svg'))
             + svg_const('VCCI-LOCKUP', os.path.join(ASSETS, '01_Logo', 'SVG', 'VCCI_Lockup_Horizontal_VI-EN.svg'))
             + ring_const() + heroes_const())
    fonts = [os.path.join(ASSETS, '03_Fonts', fam, f) for fam in ('Lora', 'BeVietnamPro')
             for f in sorted(os.listdir(os.path.join(ASSETS, '03_Fonts', fam))) if f.endswith(('.ttf', '.txt'))]
    for fmt in FORMATS:
        src, dst = os.path.join(SRC, 'formats', fmt), os.path.join(out_root, fmt)
        os.makedirs(os.path.join(dst, 'fonts'))
        template = open(os.path.join(src, 'template.typ'), encoding='utf-8').read()
        open(os.path.join(dst, 'typst-template.typ'), 'w', encoding='utf-8', newline='\n').write(
            tokens_typ() + logos + shared_typ + '\n' + template)
        for f in os.listdir(src):   # _extension.yml, typst-show.typ and format-specific filters
            if f != 'template.typ': shutil.copy(os.path.join(src, f), os.path.join(dst, f))
        for f in ('vcci.lua', 'apa.csl'):   # apa.csl: APA 7 for Word (CC BY-SA 3.0, citation-style-language/styles)
            shutil.copy(os.path.join(SRC, 'shared', f), os.path.join(dst, f))
        for f in fonts:
            name = os.path.basename(f)
            if name == 'OFL.txt': name = f'OFL-{os.path.basename(os.path.dirname(f))}.txt'
            shutil.copy(f, os.path.join(dst, 'fonts', name))
        reference_docx(os.path.join(dst, 'vcci-reference.docx'))


TEXT = ('.typ', '.yml', '.lua', '.txt', '.csl')

def same_file(a, b):
    """Byte comparison; text files ignore line endings (git core.autocrlf rewrites them on checkout)."""
    if a.endswith(TEXT):
        return open(a, 'rb').read().replace(b'\r\n', b'\n') == open(b, 'rb').read().replace(b'\r\n', b'\n')
    return filecmp.cmp(a, b, shallow=False)

def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files: return False
    return (all(same_file(os.path.join(a, f), os.path.join(b, f)) for f in cmp.common_files)
            and all(same_tree(os.path.join(a, d), os.path.join(b, d)) for d in cmp.common_dirs))


def sync(src, dst):
    """Make dst identical to src file by file (Dropbox can lock a folder, so never delete whole trees)."""
    os.makedirs(dst, exist_ok=True)
    for name in os.listdir(dst):
        if not os.path.exists(os.path.join(src, name)):
            p = os.path.join(dst, name)
            for attempt in range(5):
                try:
                    shutil.rmtree(p) if os.path.isdir(p) else os.remove(p); break
                except PermissionError:
                    time.sleep(1)
    for name in os.listdir(src):
        s, d = os.path.join(src, name), os.path.join(dst, name)
        if os.path.isdir(s): sync(s, d)
        elif not os.path.exists(d) or not same_file(s, d): shutil.copy2(s, d)


if __name__ == '__main__':
    if '--check' in sys.argv:
        with tempfile.TemporaryDirectory() as tmp:
            build(tmp)
            ok = os.path.isdir(OUT) and same_tree(tmp, OUT)
        print('extensions up to date' if ok else 'extensions OUT OF DATE: run python quarto-vcci/build.py')
        sys.exit(0 if ok else 1)
    with tempfile.TemporaryDirectory() as tmp:
        build(tmp)
        sync(tmp, OUT)
    print('built', ', '.join(FORMATS), '->', OUT)
